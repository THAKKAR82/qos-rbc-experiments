def test_encoded_representation_and_accounting(bank):
    X = bank["X_encoded"]
    assert X.shape == (45211, 51)
    assert np.count_nonzero(X) == 723376
    assert np.count_nonzero(X, axis=1).max() == bank["s"] == 16
    assert bank["qos_machine_size"] == 41
    assert bank["cv"].get_n_splits() == 5
    assert bank["cv"].shuffle is True
    assert bank["cv"].random_state == 42


@pytest.mark.parametrize("name,expected", [
    ("paper_accuracy", 0.8995155858234207),
    ("paper_balanced_accuracy", 0.6300640934600773),
    ("balanced_accuracy", 0.8256193229214974),
])
def test_baseline_metrics(bank, name, expected):
    assert bank[name].shape == (5,)
    assert_close(bank[name].mean(), expected)


@pytest.mark.parametrize("weight,metric,expected,column", [
    (None, "accuracy", 0.899537704823642, "paper_accuracy"),
    ("balanced", "balanced_accuracy", 0.8256067994399695, "balanced_accuracy"),
])
def test_csr_jl_full_dimension(bank, weight, metric, expected, column):
    X = bank["sparse_jl_features"](bank["X_full"], 51, seed=42, sparsity=1)
    assert sp.isspmatrix_csr(X)
    assert X.shape == (45211, 51)
    assert X.nnz == 723376
    assert (X != sp.csr_matrix(bank["X_full"])).nnz == 0
    scores = cross_val_score(
        RidgeClassifier(alpha=10.0, solver="auto", class_weight=weight),
        X, bank["y"], cv=bank["cv"], scoring=metric,
    )
    assert_close(scores.mean(), expected)
    saved = pd.read_csv(ROOT / "results/bank_sparse_jl_sweep_raw.csv")
    assert_close(saved.loc[saved.k == 51, column], scores.mean())


@pytest.mark.parametrize("method,accuracy,balanced", [
    ("bucket", 0.8995155858234207, 0.8256193229214974),
    ("sparse_jl", 0.899537704823642, 0.8256067994399695),
])
def test_saved_sweep_fixtures(method, accuracy, balanced):
    raw = pd.read_csv(ROOT / f"results/bank_{method}_sweep_raw.csv")
    summary = pd.read_csv(ROOT / f"results/bank_{method}_sweep_summary.csv")
    assert list(raw.columns) == ["k", "seed", "paper_accuracy", "balanced_accuracy",
                                 "streaming_size", "sparse_size", "qos_size", "max_sparsity"]
    assert list(zip(raw.k, raw.seed)) == [(k, s) for k in DIMENSIONS for s in SEEDS]
    assert summary.k.tolist() == DIMENSIONS
    assert_close(raw.streaming_size, raw.k)
    # Deliberately retain the Bank row-only convention, not reference max(row,col).
    expected_qos = (2 * np.ceil(np.log2(45211 + 2 * raw.k))
                    + np.ceil(np.log2(raw.max_sparsity + 1)) + 4)
    np.testing.assert_array_equal(raw.qos_size, expected_qos)
    endpoint = raw[raw.k == 51]
    assert_close(endpoint.paper_accuracy, accuracy)
    assert_close(endpoint.balanced_accuracy, balanced)
    assert (endpoint.sparse_size == 723376).all()
    assert (endpoint.max_sparsity == 16).all()
    assert (endpoint.qos_size == 41).all()
    grouped = raw.groupby("k", sort=True)
    for metric in ["paper_accuracy", "balanced_accuracy"]:
        assert_close(summary[f"{metric}_mean"], grouped[metric].mean())
        # pandas sample std across seed-level means, not reference flattened SEM.
        assert_close(summary[f"{metric}_std"], grouped[metric].std(ddof=1))
    for column in ["streaming_size", "sparse_size", "qos_size", "max_sparsity"]:
        assert_close(summary[column], grouped[column].mean())


def test_saved_comparison():
    comparison = pd.read_csv(ROOT / "results/bank_bucket_vs_jl_comparison.csv")
    assert comparison.k.tolist() == DIMENSIONS
    for method, suffix in [("bucket", "bucket"), ("sparse_jl", "jl")]:
        summary = pd.read_csv(ROOT / f"results/bank_{method}_sweep_summary.csv")
        for field in ["paper_accuracy_mean", "balanced_accuracy_mean",
                      "streaming_size", "sparse_size", "qos_size"]:
            assert_close(comparison[f"{field}_{suffix}"], summary[field])
    for prefix, field in [("paper_acc", "paper_accuracy_mean"),
                          ("balanced_acc", "balanced_accuracy_mean")]:
        assert_close(comparison[f"{prefix}_delta_jl_minus_bucket"],
                     comparison[f"{field}_jl"] - comparison[f"{field}_bucket"])
